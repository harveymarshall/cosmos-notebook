#!/usr/bin/env bash
# One-time migration helper: reads the live CloudFormation stack and writes
#   infra/terraform/existing.auto.tfvars  - generated names Terraform must keep
#   infra/terraform/imports.tf            - import blocks so Terraform adopts (not recreates)
#                                          every live resource
# Read-only: it only describes resources. Run by the "discover" step of
# .github/workflows/infra.yml, or by hand in AWS CloudShell.
set -euo pipefail

STACK="${STACK:-cosmos-notebook}"
REGION="${AWS_REGION:-eu-west-2}"
OUT="$(cd "$(dirname "$0")/.." && pwd)"

resources=$(aws cloudformation describe-stack-resources --region "$REGION" --stack-name "$STACK" \
  --query 'StackResources[].[LogicalResourceId,PhysicalResourceId]' --output text)
id() {
  local v
  v=$(awk -v k="$1" '$1 == k { print $2 }' <<<"$resources")
  [ -n "$v" ] || { echo "Stack $STACK has no resource $1" >&2; exit 1; }
  printf '%s' "$v"
}
has() { awk -v k="$1" '$1 == k { f = 1 } END { exit !f }' <<<"$resources"; }

BUCKET=$(id SiteBucket)
POOL=$(id UserPool)
CLIENT=$(id UserPoolClient)
TABLE=$(id Table)
API_ROLE=$(id ApiFunctionRole)
FUNCTION=$(id ApiFunction)
API=$(id HttpApi)
AUTHORIZER=$(id ApiAuthorizer)
INTEGRATION=$(id ApiIntegration)
OAC=$(id OriginAccessControl)
CACHE_POLICY=$(id ApiCachePolicy)
DISTRIBUTION=$(id Distribution)
DEPLOY_ROLE=$(id GitHubDeployRole)
LOG_GROUP=$(id ApiLogGroup)
CF_FUNCTION=$(aws cloudfront describe-function --name "${STACK}-index-rewrite" --query 'FunctionSummary.Name' --output text)

# The invoke permission's statement ID is generated; read it from the function's policy.
STATEMENT=$(aws lambda get-policy --region "$REGION" --function-name "$FUNCTION" --query Policy --output text |
  jq -r '.Statement[] | select(.Principal.Service == "apigateway.amazonaws.com") | .Sid' | head -1)
[ -n "$STATEMENT" ] || { echo "No API Gateway permission found on $FUNCTION" >&2; exit 1; }

R_HEALTH=$(id RouteHealth)
R_LIBRARY=$(id RouteLibrary)
R_FEED=$(id RouteFeed)
R_POST=$(id RoutePost)
R_COMMENTS=$(id RouteComments)
R_PRIVATE=$(id RoutePrivate)

cat >"$OUT/existing.auto.tfvars" <<EOF
# Generated by scripts/discover.sh from the CloudFormation stack "$STACK".
# These resources were created with generated names; keeping them stops Terraform replacing them.
site_bucket_name        = "$BUCKET"
table_name              = "$TABLE"
api_role_name           = "$API_ROLE"
deploy_role_name        = "$DEPLOY_ROLE"
api_invoke_statement_id = "$STATEMENT"
EOF

OIDC=""
if has GitHubOIDCProvider; then OIDC=$(id GitHubOIDCProvider); fi

imp() { printf 'import {\n  to = %s\n  id = "%s"\n}\n\n' "$1" "$2"; }
{
  echo "# Generated by scripts/discover.sh: adopts the resources CloudFormation created."
  echo "# Import blocks do nothing once the resources are in Terraform state; delete this file"
  echo "# after the migration is finished."
  echo
  imp aws_s3_bucket.site "$BUCKET"
  imp aws_s3_bucket_public_access_block.site "$BUCKET"
  imp aws_s3_bucket_ownership_controls.site "$BUCKET"
  imp aws_s3_bucket_server_side_encryption_configuration.site "$BUCKET"
  imp aws_s3_bucket_policy.site "$BUCKET"
  imp aws_cloudfront_origin_access_control.site "$OAC"
  imp aws_cloudfront_function.index_rewrite "$CF_FUNCTION"
  imp aws_cloudfront_cache_policy.api "$CACHE_POLICY"
  imp aws_cloudfront_distribution.site "$DISTRIBUTION"
  imp aws_cognito_user_pool.members "$POOL"
  imp aws_cognito_user_pool_client.web "$POOL/$CLIENT"
  imp aws_cognito_user_group.admins "$POOL/admins"
  imp aws_dynamodb_table.main "$TABLE"
  imp aws_cloudwatch_log_group.api "$LOG_GROUP"
  imp aws_iam_role.api "$API_ROLE"
  imp aws_iam_role_policy_attachment.api_logs "$API_ROLE/arn:aws:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole"
  imp aws_iam_role_policy.api_table "$API_ROLE:table-access"
  imp aws_lambda_function.api "$FUNCTION"
  imp aws_lambda_permission.api_gateway "$FUNCTION/$STATEMENT"
  imp aws_apigatewayv2_api.api "$API"
  imp aws_apigatewayv2_authorizer.cognito "$API/$AUTHORIZER"
  imp aws_apigatewayv2_integration.lambda "$API/$INTEGRATION"
  imp 'aws_apigatewayv2_route.public["health"]' "$API/$R_HEALTH"
  imp 'aws_apigatewayv2_route.public["library"]' "$API/$R_LIBRARY"
  imp 'aws_apigatewayv2_route.public["feed"]' "$API/$R_FEED"
  imp 'aws_apigatewayv2_route.public["post"]' "$API/$R_POST"
  imp 'aws_apigatewayv2_route.public["comments"]' "$API/$R_COMMENTS"
  imp aws_apigatewayv2_route.private "$API/$R_PRIVATE"
  imp aws_apigatewayv2_stage.default "$API/\$default"
  if has GitHubOIDCProvider; then
    imp 'aws_iam_openid_connect_provider.github[0]' "$OIDC"
  fi
  imp aws_iam_role.deploy "$DEPLOY_ROLE"
  imp aws_iam_role_policy.deploy "$DEPLOY_ROLE:deploy-site"
} | sed '$ d' >"$OUT/imports.tf"

if ! has GitHubOIDCProvider; then
  echo 'create_github_oidc_provider = false' >>"$OUT/existing.auto.tfvars"
fi

echo "Wrote $OUT/existing.auto.tfvars and $OUT/imports.tf"
